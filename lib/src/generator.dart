import 'model.dart';

final class FlutterWidgetGenerator {
  late LayoutDocument _document;
  var _sourceMarkers = false;

  String generate(LayoutDocument document, {bool sourceMarkers = false}) {
    _document = document;
    _sourceMarkers = sourceMarkers;
    final externalVariables = document.variables
        .where((variable) => variable.ownership == VariableOwnership.external)
        .toList(growable: false);
    final ownedVariables = document.variables
        .where((variable) => variable.ownership == VariableOwnership.owned)
        .toList(growable: false);
    final fields = document.variables
        .map((variable) => '  final ${variable.type} ${variable.name};')
        .join('\n');
    final parameters = document.variables
        .map((variable) => '    required this.${variable.name},')
        .join('\n');
    final widget = _emitWidget(document.root, 2);
    final imports = <String>{
      for (final entry in document.imports.entries)
        "import '${entry.value}' as ${entry.key};",
      for (final variable in document.variables)
        if (variable.import case final import?) "import '$import';",
      for (final include in document.includes.values)
        "import '${include.importUri}';",
    }.join('\n');
    final host = ownedVariables.isEmpty
        ? ''
        : _emitOwnedHost(document, externalVariables, ownedVariables);

    return '''
// Generated by SpokeML. Do not edit.
import 'package:flutter/material.dart';
${imports.isEmpty ? '' : '$imports\n'}

class ${document.className} extends StatelessWidget {
  const ${document.className}({
    super.key,
${parameters.isEmpty ? '' : '$parameters\n'}  });

${fields.isEmpty ? '' : '$fields\n\n'}  @override
  Widget build(BuildContext context) {
    return $widget;
  }
}
$host
''';
  }

  String _emitOwnedHost(
    LayoutDocument document,
    List<LayoutVariable> externalVariables,
    List<LayoutVariable> ownedVariables,
  ) {
    final hostName = '${document.className}Host';
    final parameters = externalVariables
        .map((variable) => '    required this.${variable.name},')
        .join('\n');
    final fields = externalVariables
        .map((variable) => '  final ${variable.type} ${variable.name};')
        .join('\n');
    final ownedFields = ownedVariables
        .map(
          (variable) =>
              '  late final ${variable.type} ${variable.name} = '
              '${_markValue(variable.create!, variable.create!.source)};',
        )
        .join('\n');
    final disposeCalls = ownedVariables
        .where((variable) => variable.dispose != 'none')
        .map(
          (variable) =>
              '    ${variable.name}.${variable.dispose ?? 'dispose'}();',
        )
        .join('\n');
    final viewArguments = document.variables
        .map((variable) {
          final source = variable.ownership == VariableOwnership.external
              ? 'widget.${variable.name}'
              : variable.name;
          return '      ${variable.name}: $source,';
        })
        .join('\n');
    return '''

class $hostName extends StatefulWidget {
  const $hostName({
    super.key,
${parameters.isEmpty ? '' : '$parameters\n'}  });

${fields.isEmpty ? '' : '$fields\n\n'}  @override
  State<$hostName> createState() => _${hostName}State();
}

class _${hostName}State extends State<$hostName> {
$ownedFields

  @override
  void dispose() {
${disposeCalls.isEmpty ? '' : '$disposeCalls\n'}    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return ${document.className}(
$viewArguments
    );
  }
}
''';
  }

  String _emitWidget(WidgetNode node, int depth) {
    final attributes = Map<String, LayoutValue>.of(node.attributes);
    final visible = attributes.remove('visible');
    final condition = attributes.remove('if');
    final key = attributes.remove('key');
    final wrapperCount = [visible, key].whereType<LayoutValue>().length;
    final widgetDepth = depth + wrapperCount;
    var emitted = node.namespacePrefix == null
        ? switch (node.name) {
            'Observe' => _emitObserve(node, attributes, widgetDepth),
            'Include' => _emitInclude(node, attributes, widgetDepth),
            'ForEach' || 'Builder' || 'Slot' => throw SpokeMlCompileException(
              '<${node.name}> is only valid in a children or builder slot.',
              location: node.location,
            ),
            'Text' => _emitText(node, attributes, widgetDepth),
            'Column' => _emitFlex(node, attributes, widgetDepth, 'Column'),
            'Row' => _emitFlex(node, attributes, widgetDepth, 'Row'),
            'Stack' => _emitStack(node, attributes, widgetDepth),
            'Positioned' => _emitPositioned(node, attributes, widgetDepth),
            'Align' => _emitAlign(node, attributes, widgetDepth),
            'Container' => _emitContainer(node, attributes, widgetDepth),
            'Padding' => _emitPadding(node, attributes, widgetDepth),
            'Center' => _emitSingleChild(
              node,
              attributes,
              widgetDepth,
              'Center',
            ),
            'SizedBox' => _emitSizedBox(node, attributes, widgetDepth),
            'ElevatedButton' => _emitButton(node, attributes, widgetDepth),
            'CircularProgressIndicator' => _emitProgress(
              node,
              attributes,
              widgetDepth,
            ),
            _ when node.name.contains('.') => _emitCustomWidget(
              node,
              attributes,
              widgetDepth,
            ),
            _ => throw SpokeMlCompileException(
              'Unsupported widget <${node.name}>.',
              location: node.location,
            ),
          }
        : _emitCustomWidget(node, attributes, widgetDepth);

    var currentDepth = widgetDepth - 1;
    if (key != null) {
      emitted =
          '''KeyedSubtree(
${_indent(currentDepth + 1)}key: ${_bindingExpression(key, node)},
${_indent(currentDepth + 1)}child: $emitted,
${_indent(currentDepth)})''';
      currentDepth--;
    }
    if (visible != null) {
      emitted =
          '''Visibility(
${_indent(currentDepth + 1)}visible: ${_bool(visible, node, 'visible')},
${_indent(currentDepth + 1)}child: $emitted,
${_indent(currentDepth)})''';
      currentDepth--;
    }
    if (condition != null) {
      emitted =
          '${_bool(condition, node, 'if')} ? $emitted : const SizedBox.shrink()';
    }
    return '${_indent(depth)}${_mark(node.location, emitted)}';
  }

  String _emitInclude(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, maximum: 0);
    final layout = attributes.remove('layout');
    if (layout is! LiteralValue) {
      throw SpokeMlCompileException(
        '<Include> requires a literal "layout" path.',
        location: layout?.location ?? node.location,
      );
    }
    final include = _document.includes[layout.source];
    if (include == null) {
      throw SpokeMlCompileException(
        'Include "${layout.source}" was not resolved. Compile layouts through '
        'build_runner so file dependencies can be loaded.',
        location: layout.location,
      );
    }
    for (final entry in attributes.entries) {
      if (!include.variables.contains(entry.key)) {
        throw SpokeMlCompileException(
          '<Include layout="${layout.source}"> does not define variable '
          '"${entry.key}".',
          location: entry.value.location,
        );
      }
    }
    final missing = include.variables.difference(attributes.keys.toSet());
    if (missing.isNotEmpty) {
      throw SpokeMlCompileException(
        '<Include layout="${layout.source}"> requires variable '
        '"${missing.first}".',
        location: node.location,
      );
    }
    return _constructor(
      include.className,
      [
        for (final entry in attributes.entries)
          '${entry.key}: ${_customValue(entry.value)}',
      ],
      depth,
      constWhenEmpty: false,
    );
  }

  String _emitObserve(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, minimum: 1, maximum: 1);
    final listenable = attributes.remove('listenable');
    final valueListenable = attributes.remove('valueListenable');
    final stream = attributes.remove('stream');
    final alias = attributes.remove('as');
    _rejectAttributes(node, attributes);

    final sourceCount = [
      listenable,
      valueListenable,
      stream,
    ].whereType<LayoutValue>().length;
    if (sourceCount != 1) {
      throw SpokeMlCompileException(
        '<Observe> requires exactly one of "listenable", "valueListenable", '
        'or "stream".',
        location: node.location,
      );
    }
    final child = _emitWidget(node.children.single, depth + 1);
    if (listenable != null) {
      if (alias != null) {
        throw SpokeMlCompileException(
          '<Observe as="..."> is only valid with "valueListenable" or '
          '"stream".',
          location: alias.location,
        );
      }
      return '''ListenableBuilder(
${_indent(depth + 1)}listenable: ${_bindingExpression(listenable, node)},
${_indent(depth + 1)}builder: (context, _) {
${_indent(depth + 2)}return $child;
${_indent(depth + 1)}},
${_indent(depth)})''';
    }

    if (alias is! LiteralValue) {
      throw SpokeMlCompileException(
        '<Observe valueListenable="..."> and <Observe stream="..."> require '
        'a literal "as" alias.',
        location: alias?.location ?? node.location,
      );
    }
    if (valueListenable != null) {
      return '''ValueListenableBuilder(
${_indent(depth + 1)}valueListenable: ${_bindingExpression(valueListenable, node)},
${_indent(depth + 1)}builder: (context, ${alias.source}, _) {
${_indent(depth + 2)}return $child;
${_indent(depth + 1)}},
${_indent(depth)})''';
    }
    return '''StreamBuilder(
${_indent(depth + 1)}stream: ${_bindingExpression(stream!, node)},
${_indent(depth + 1)}builder: (context, ${alias.source}) {
${_indent(depth + 2)}return $child;
${_indent(depth + 1)}},
${_indent(depth)})''';
  }

  String _emitCustomWidget(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    final positionalEntries = attributes.entries
        .where((entry) => RegExp(r'^arg\d+$').hasMatch(entry.key))
        .toList()
      ..sort(
        (left, right) => int.parse(
          left.key.substring(3),
        ).compareTo(int.parse(right.key.substring(3))),
      );
    for (var index = 0; index < positionalEntries.length; index++) {
      final actualIndex = int.parse(positionalEntries[index].key.substring(3));
      if (actualIndex != index) {
        throw SpokeMlCompileException(
          '<${node.name}> positional arguments must be contiguous from '
          '"arg0"; found "${positionalEntries[index].key}".',
          location: positionalEntries[index].value.location,
        );
      }
    }
    for (final entry in positionalEntries) {
      attributes.remove(entry.key);
    }
    final builders = node.children
        .where(
          (child) => child.namespacePrefix == null && child.name == 'Builder',
        )
        .toList();
    final slots = node.children
        .where(
          (child) => child.namespacePrefix == null && child.name == 'Slot',
        )
        .toList();
    final widgetChildren = node.children
        .where(
          (child) =>
              child.namespacePrefix != null ||
              (child.name != 'Builder' && child.name != 'Slot'),
        )
        .toList();
    final arguments = <String>[
      for (final entry in positionalEntries) _customValue(entry.value),
      for (final attribute in attributes.entries)
        '${attribute.key}: ${_customValue(attribute.value)}',
      for (final slot in slots) _emitSlotArgument(slot, depth + 1),
      for (final builder in builders) _emitBuilderArgument(builder, depth + 1),
    ];
    final containsCollection = widgetChildren.any(
      (child) => child.namespacePrefix == null && child.name == 'ForEach',
    );
    if (widgetChildren.length == 1 && !containsCollection) {
      arguments.add('child: ${_emitWidget(widgetChildren.single, depth + 1)}');
    } else if (widgetChildren.isNotEmpty) {
      arguments.add(_children(widgetChildren, depth + 1));
    }
    final type = node.namespacePrefix == null
        ? node.name
        : '${node.namespacePrefix}.${node.name}';
    return _constructor(type, arguments, depth, constWhenEmpty: false);
  }

  String _emitSlotArgument(WidgetNode node, int depth) {
    _expectChildren(node, minimum: 1, maximum: 1);
    final attributes = Map<String, LayoutValue>.of(node.attributes);
    final name = _literalIdentifier(
      _required(attributes, 'name', node),
      node,
      'name',
    );
    _rejectAttributes(node, attributes);
    return '$name: ${_emitWidget(node.children.single, depth + 1)}';
  }

  String _emitBuilderArgument(WidgetNode node, int depth) {
    _expectChildren(node, minimum: 1, maximum: 1);
    final attributes = Map<String, LayoutValue>.of(node.attributes);
    final name = _literalIdentifier(
      _required(attributes, 'name', node),
      node,
      'name',
    );
    final argsValue = attributes.remove('args');
    final arguments = argsValue == null
        ? const <String>[]
        : _literalIdentifierList(argsValue, node, 'args');
    _rejectAttributes(node, attributes);
    final child = _emitWidget(node.children.single, depth + 1);
    return '''$name: (${arguments.join(', ')}) {
${_indent(depth + 1)}return $child;
${_indent(depth)}}''';
  }

  String _customValue(LayoutValue value) {
    final String converted;
    if (value case BindingValue(:final source)) {
      converted = source;
    } else if (value.source == 'true' || value.source == 'false') {
      converted = value.source;
    } else if (num.tryParse(value.source) case final number?) {
      converted = number.toString();
    } else {
      converted = "'${_escape(value.source)}'";
    }
    return _markValue(value, converted);
  }

  String _emitText(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, maximum: 0);
    final text = _required(attributes, 'text', node);
    final arguments = <String>[_string(text)];
    _add(arguments, 'style', attributes.remove('style'), _textStyle);
    _addEnum(arguments, 'textAlign', attributes, 'TextAlign', node);
    _addInt(arguments, 'maxLines', attributes, node);
    _addEnum(arguments, 'overflow', attributes, 'TextOverflow', node);
    _rejectAttributes(node, attributes);
    return _constructor('Text', arguments, depth);
  }

  String _emitFlex(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
    String type,
  ) {
    final arguments = <String>[];
    _addEnum(
      arguments,
      'mainAxisAlignment',
      attributes,
      'MainAxisAlignment',
      node,
    );
    _addEnum(
      arguments,
      'crossAxisAlignment',
      attributes,
      'CrossAxisAlignment',
      node,
    );
    _addEnum(arguments, 'mainAxisSize', attributes, 'MainAxisSize', node);
    _rejectAttributes(node, attributes);
    arguments.add(_children(node.children, depth + 1));
    return _constructor(type, arguments, depth);
  }

  String _emitStack(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    final arguments = <String>[];
    _add(arguments, 'alignment', attributes.remove('alignment'), _alignment);
    _addEnum(arguments, 'textDirection', attributes, 'TextDirection', node);
    _addEnum(arguments, 'fit', attributes, 'StackFit', node);
    _addEnum(arguments, 'clipBehavior', attributes, 'Clip', node);
    _rejectAttributes(node, attributes);
    arguments.add(_children(node.children, depth + 1));
    return _constructor('Stack', arguments, depth);
  }

  String _emitPositioned(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, minimum: 1, maximum: 1);
    final arguments = <String>[];
    for (final name in ['left', 'top', 'right', 'bottom', 'width', 'height']) {
      _addNum(arguments, name, attributes, node);
    }
    _rejectAttributes(node, attributes);
    arguments.add('child: ${_emitWidget(node.children.single, depth + 1)}');
    return _constructor('Positioned', arguments, depth);
  }

  String _emitAlign(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, minimum: 1, maximum: 1);
    final arguments = <String>[];
    _add(arguments, 'alignment', attributes.remove('alignment'), _alignment);
    _addNum(arguments, 'widthFactor', attributes, node);
    _addNum(arguments, 'heightFactor', attributes, node);
    _rejectAttributes(node, attributes);
    arguments.add('child: ${_emitWidget(node.children.single, depth + 1)}');
    return _constructor('Align', arguments, depth);
  }

  String _emitContainer(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, maximum: 1);
    final arguments = <String>[];
    _addNum(arguments, 'width', attributes, node);
    _addNum(arguments, 'height', attributes, node);
    _add(arguments, 'padding', attributes.remove('padding'), _edgeInsets);
    _add(arguments, 'margin', attributes.remove('margin'), _edgeInsets);
    _add(arguments, 'color', attributes.remove('color'), _color);
    _add(arguments, 'alignment', attributes.remove('alignment'), _alignment);
    _rejectAttributes(node, attributes);
    if (node.children.isNotEmpty) {
      arguments.add('child: ${_emitWidget(node.children.single, depth + 1)}');
    }
    return _constructor('Container', arguments, depth);
  }

  String _emitPadding(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, minimum: 1, maximum: 1);
    final padding = _required(attributes, 'padding', node);
    _rejectAttributes(node, attributes);
    return _constructor('Padding', [
      'padding: ${_edgeInsets(padding)}',
      'child: ${_emitWidget(node.children.single, depth + 1)}',
    ], depth);
  }

  String _emitSingleChild(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
    String type,
  ) {
    _expectChildren(node, minimum: 1, maximum: 1);
    _rejectAttributes(node, attributes);
    return _constructor(type, [
      'child: ${_emitWidget(node.children.single, depth + 1)}',
    ], depth);
  }

  String _emitSizedBox(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, maximum: 1);
    final arguments = <String>[];
    _addNum(arguments, 'width', attributes, node);
    _addNum(arguments, 'height', attributes, node);
    _rejectAttributes(node, attributes);
    if (node.children.isNotEmpty) {
      arguments.add('child: ${_emitWidget(node.children.single, depth + 1)}');
    }
    return _constructor('SizedBox', arguments, depth);
  }

  String _emitButton(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, minimum: 1, maximum: 1);
    final onPressed = _required(attributes, 'onPressed', node);
    if (onPressed is! BindingValue) {
      throw SpokeMlCompileException(
        '<${node.name}> attribute "onPressed" must be a binding.',
        location: onPressed.location,
      );
    }
    _rejectAttributes(node, attributes);
    return _constructor('ElevatedButton', [
      'onPressed: ${_markValue(onPressed, onPressed.source)}',
      'child: ${_emitWidget(node.children.single, depth + 1)}',
    ], depth);
  }

  String _emitProgress(
    WidgetNode node,
    Map<String, LayoutValue> attributes,
    int depth,
  ) {
    _expectChildren(node, maximum: 0);
    final arguments = <String>[];
    _addNum(arguments, 'value', attributes, node);
    _rejectAttributes(node, attributes);
    return _constructor('CircularProgressIndicator', arguments, depth);
  }

  String _constructor(
    String type,
    List<String> arguments,
    int depth, {
    bool constWhenEmpty = true,
  }) {
    if (arguments.isEmpty) {
      return '${constWhenEmpty ? 'const ' : ''}$type()';
    }
    final indentation = _indent(depth + 1);
    final closing = _indent(depth);
    return '$type(\n'
        '${arguments.map((argument) => '$indentation$argument,').join('\n')}\n'
        '$closing)';
  }

  String _children(List<WidgetNode> children, int depth) {
    if (children.isEmpty) {
      return 'children: const []';
    }
    final indentation = _indent(depth + 1);
    final closing = _indent(depth);
    return 'children: [\n'
        '${children.map((child) {
          if (child.namespacePrefix == null && child.name == 'ForEach') {
            return '$indentation${_emitForEach(child, depth + 1)}';
          }
          return '$indentation${_emitWidget(child, depth + 1)},';
        }).join('\n')}\n'
        '$closing]';
  }

  String _emitForEach(WidgetNode node, int depth) {
    _expectChildren(node, minimum: 1, maximum: 1);
    final attributes = Map<String, LayoutValue>.of(node.attributes);
    final items = _required(attributes, 'items', node);
    final item = _literalIdentifier(
      _required(attributes, 'as', node),
      node,
      'as',
    );
    final indexValue = attributes.remove('index');
    final index = indexValue == null
        ? '_'
        : _literalIdentifier(indexValue, node, 'index');
    final keyBy = _required(attributes, 'keyBy', node);
    _rejectAttributes(node, attributes);
    final child = _emitWidget(node.children.single, depth + 1);
    return '''for (final ($index, $item) in ${_bindingExpression(items, node)}.indexed)
${_indent(depth + 1)}KeyedSubtree(
${_indent(depth + 2)}key: ValueKey(${_bindingExpression(keyBy, node)}),
${_indent(depth + 2)}child: $child,
${_indent(depth + 1)}),''';
  }

  String _literalIdentifier(
    LayoutValue value,
    WidgetNode node,
    String attribute,
  ) {
    if (value case LiteralValue(
      :final source,
    ) when RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$').hasMatch(source)) {
      return source;
    }
    throw SpokeMlCompileException(
      '<${node.name}> attribute "$attribute" must be a literal Dart '
      'identifier.',
      location: value.location,
    );
  }

  List<String> _literalIdentifierList(
    LayoutValue value,
    WidgetNode node,
    String attribute,
  ) {
    if (value is! LiteralValue) {
      throw SpokeMlCompileException(
        '<${node.name}> attribute "$attribute" must be a comma-separated '
        'literal identifier list.',
        location: value.location,
      );
    }
    final values = value.source
        .split(',')
        .map((part) => part.trim())
        .where((part) => part.isNotEmpty)
        .toList();
    for (final name in values) {
      _literalIdentifier(LiteralValue(name, value.location), node, attribute);
    }
    return values;
  }

  LayoutValue _required(
    Map<String, LayoutValue> attributes,
    String name,
    WidgetNode node,
  ) {
    final value = attributes.remove(name);
    if (value == null) {
      throw SpokeMlCompileException(
        '<${node.name}> requires attribute "$name".',
        location: node.location,
      );
    }
    return value;
  }

  void _add(
    List<String> arguments,
    String name,
    LayoutValue? value,
    String Function(LayoutValue) convert,
  ) {
    if (value != null) {
      arguments.add('$name: ${convert(value)}');
    }
  }

  void _addEnum(
    List<String> arguments,
    String name,
    Map<String, LayoutValue> attributes,
    String type,
    WidgetNode node,
  ) {
    final value = attributes.remove(name);
    if (value == null) return;
    arguments.add('$name: ${_enum(value, type, node, name)}');
  }

  void _addNum(
    List<String> arguments,
    String name,
    Map<String, LayoutValue> attributes,
    WidgetNode node,
  ) {
    final value = attributes.remove(name);
    if (value == null) return;
    arguments.add('$name: ${_num(value, node, name)}');
  }

  void _addInt(
    List<String> arguments,
    String name,
    Map<String, LayoutValue> attributes,
    WidgetNode node,
  ) {
    final value = attributes.remove(name);
    if (value == null) return;
    if (value case BindingValue(:final source)) {
      arguments.add('$name: ${_markValue(value, source)}');
    } else if (int.tryParse(value.source) case final parsed?) {
      arguments.add('$name: ${_markValue(value, parsed.toString())}');
    } else {
      throw SpokeMlCompileException(
        '<${node.name}> attribute "$name" must be an integer.',
        location: value.location,
      );
    }
  }

  String _string(LayoutValue value) {
    final converted = switch (value) {
      BindingValue(:final source) => source,
      LiteralValue(:final source) => "'${_escape(source)}'",
    };
    return _markValue(value, converted);
  }

  String _bool(LayoutValue value, WidgetNode node, String name) {
    if (value case BindingValue(:final source)) {
      return _markValue(value, source);
    }
    if (value.source == 'true' || value.source == 'false') {
      return _markValue(value, value.source);
    }
    throw SpokeMlCompileException(
      '<${node.name}> attribute "$name" must be true, false, or a binding.',
      location: value.location,
    );
  }

  String _num(LayoutValue value, WidgetNode node, String name) {
    if (value case BindingValue(:final source)) {
      return _markValue(value, source);
    }
    final number = num.tryParse(value.source);
    if (number == null) {
      throw SpokeMlCompileException(
        '<${node.name}> attribute "$name" must be a number.',
        location: value.location,
      );
    }
    return _markValue(value, number.toString());
  }

  String _enum(LayoutValue value, String type, WidgetNode node, String name) {
    if (value case BindingValue(:final source)) {
      return _markValue(value, source);
    }
    if (!RegExp(r'^[A-Za-z][A-Za-z0-9]*$').hasMatch(value.source)) {
      throw SpokeMlCompileException(
        '<${node.name}> attribute "$name" has invalid enum value '
        '"${value.source}".',
        location: value.location,
      );
    }
    return _markValue(value, '$type.${value.source}');
  }

  String _edgeInsets(LayoutValue value) {
    if (value case BindingValue(:final source)) {
      return _markValue(value, source);
    }
    final parts = value.source.split(',').map((part) => part.trim()).toList();
    final values = parts.map(num.tryParse).toList();
    if (values.any((value) => value == null) ||
        (values.length != 1 && values.length != 4)) {
      throw SpokeMlCompileException(
        'Insets must contain one number or four comma-separated numbers, '
        'found "${value.source}".',
        location: value.location,
      );
    }
    if (values.length == 1) {
      return _markValue(value, 'EdgeInsets.all(${values.single})');
    }
    return _markValue(value, 'EdgeInsets.fromLTRB(${values.join(', ')})');
  }

  String _color(LayoutValue value) {
    if (value case BindingValue(:final source)) {
      return _markValue(value, source);
    }
    final hex = value.source.replaceFirst('#', '');
    if (!RegExp(r'^(?:[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$').hasMatch(hex)) {
      throw SpokeMlCompileException(
        'Color must use #RRGGBB or #AARRGGBB, found "${value.source}".',
        location: value.location,
      );
    }
    return _markValue(
      value,
      'Color(0x${hex.length == 6 ? 'FF' : ''}${hex.toUpperCase()})',
    );
  }

  String _alignment(LayoutValue value) {
    if (value case BindingValue(:final source)) {
      return _markValue(value, source);
    }
    const supported = {
      'topLeft',
      'topCenter',
      'topRight',
      'centerLeft',
      'center',
      'centerRight',
      'bottomLeft',
      'bottomCenter',
      'bottomRight',
    };
    if (!supported.contains(value.source)) {
      throw SpokeMlCompileException(
        'Unsupported alignment "${value.source}".',
        location: value.location,
      );
    }
    return _markValue(value, 'Alignment.${value.source}');
  }

  String _textStyle(LayoutValue value) {
    if (value case BindingValue(:final source)) {
      return _markValue(value, source);
    }
    if (!RegExp(r'^[A-Za-z][A-Za-z0-9]*$').hasMatch(value.source)) {
      throw SpokeMlCompileException(
        'Invalid text style "${value.source}".',
        location: value.location,
      );
    }
    return _markValue(value, 'Theme.of(context).textTheme.${value.source}');
  }

  void _expectChildren(
    WidgetNode node, {
    int minimum = 0,
    required int maximum,
  }) {
    if (node.children.length < minimum || node.children.length > maximum) {
      final expectation = minimum == maximum
          ? 'exactly $minimum'
          : 'between $minimum and $maximum';
      throw SpokeMlCompileException(
        '<${node.name}> requires $expectation child widgets.',
        location: node.location,
      );
    }
  }

  void _rejectAttributes(WidgetNode node, Map<String, LayoutValue> attributes) {
    if (attributes.isNotEmpty) {
      throw SpokeMlCompileException(
        '<${node.name}> does not support attribute '
        '"${attributes.keys.first}".',
        location: attributes.values.first.location,
      );
    }
  }

  String _escape(String value) => value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');

  String _indent(int depth) => '  ' * depth;

  String _bindingExpression(LayoutValue value, WidgetNode node) {
    if (value case BindingValue(:final source)) {
      return _markValue(value, source);
    }
    throw SpokeMlCompileException(
      '<${node.name}> requires a binding expression.',
      location: value.location,
    );
  }

  String _markValue(LayoutValue value, String source) =>
      _mark(value.valueLocation, source);

  String _mark(SourceLocation location, String source) {
    if (!_sourceMarkers) return source;
    final key = '${location.offset}:${location.length}';
    return '/* spoke_ml:$key */ $source';
  }
}
